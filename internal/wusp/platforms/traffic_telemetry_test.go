func TestParseIPTablesSaveCounters(t *testing.T) {
	out := `# Generated by iptables-save
*filter
:INPUT ACCEPT [100:5000]
[12:720] -A INPUT -i lo -m comment --comment "!fw3" -j ACCEPT
[340:20400] -A zone_wan_input -m comment --comment "!fw3: ban_backhaul" -j DROP
[0:0] -A zone_wan_input -p udp -m udp --dport 68 -m comment --comment "!fw3: Allow-DHCP-Renew" -j ACCEPT
COMMIT
*nat
[5:300] -A POSTROUTING -o eth0 -j MASQUERADE
COMMIT
`
	rules := parseIPTablesSaveCounters(out)
	if len(rules) != 4 {
		t.Fatalf("got %d rules", len(rules))
	}
	if rules[1].Name != "ban_backhaul" || rules[1].Target != "DROP" || rules[1].Packets != 340 || rules[1].Bytes != 20400 || rules[1].Table != "filter" {
		t.Fatalf("unexpected %+v", rules[1])
	}
	if rules[0].Name != "INPUT #1" || rules[3].Table != "nat" || rules[3].Target != "MASQUERADE" {
		t.Fatalf("unexpected %+v / %+v", rules[0], rules[3])
	}
	top := topFirewallRules(rules)
	if len(top) != 4 || top[0].Table != "filter" {
		t.Fatalf("top %+v", top)
	}
	if again := parseIPTablesSaveCounters(out); again[1].Key != rules[1].Key {
		t.Fatal("rule alias must be stable")
	}
}

