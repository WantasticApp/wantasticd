func TestTrafficTelemetryRatesAndHistory(t *testing.T) {
	clock := time.Date(2026, 10, 23, 1, 0, 0, 0, time.UTC)
	rx := uint64(1_000_000)
	pk := uint64(100)
	c := newTrafficTelemetryCoordinator(trafficTelemetryDeps{
		listIfaces: func(string) []string { return []string{"br-lan"} },
		counters: func(string, string) wifiIfaceCounters {
			return wifiIfaceCounters{RxBytes: rx, TxBytes: rx * 2, RxPackets: pk, TxPackets: pk, OK: true}
		},
		operstate: func(string, string) string { return "Up" },
		firewall: func(context.Context) ([]firewallRuleCounter, string) {
			return []firewallRuleCounter{{Key: "fw-1", Table: "filter", Chain: "INPUT", Name: "ban", Target: "DROP", Packets: pk, Bytes: rx}}, "iptables"
		},
	})
	c.now = func() time.Time { return clock }
	c.started = true
	c.sample(context.Background())
	clock = clock.Add(time.Minute)
	rx += 7_500_000 // 1 Mbit/s over 60 s
	pk += 600       // 10 pps
	c.sample(context.Background())
	snap := c.snapshotAndStart("")
	iface := snap.Interfaces[0]
	if !iface.RatesOK || iface.RxRate != 1000 || iface.TxRate != 2000 || iface.RxPPS != 10 {
		t.Fatalf("interface rates %+v", iface)
	}
	if rule := snap.Rules[0]; !rule.RatesOK || rule.PPS != 10 || rule.Kbps != 1000 {
		t.Fatalf("rule rates %+v", rule)
	}
	msg := &wusp.Message{}
	if err := appendTrafficTelemetrySnapshotFields(msg, snap); err != nil {
		t.Fatal(err)
	}
	var block []byte
	for _, f := range msg.Fields {
		if f.Path == wusp.WUSPTrafficTelemetryPrefix+"Interface.1.History" {
			block = f.Val.AsBytes()
		}
	}
	history, err := wusp.DecodeWiFiHistoryBlock(block)
	if err != nil || len(history) != 1 || history[0].Values[wusp.TrafficMetricRxRate] != 1000 {
		t.Fatalf("history %+v %v", history, err)
	}
}

func TestParseBridgeFDB(t *testing.T) {
	rec := func(mac []byte, port int, local byte, ticks uint32) []byte {
		b := make([]byte, 16)
		copy(b, mac)
		b[6], b[7], b[12] = byte(port), local, byte(port>>8)
		binary.NativeEndian.PutUint32(b[8:], ticks)
		return b
	}
	raw := append(rec([]byte{0xc8, 0x4f, 0x86, 0xa5, 0x52, 0x30}, 2, 0, 1250), rec([]byte{0xe0, 0x5d, 0x54, 0x4b, 0xe5, 0x16}, 1, 1, 0)...)
	raw = append(raw, rec([]byte{0x01, 0, 0x5e, 0, 0, 1}, 3, 0, 0)...)
	got := parseBridgeFDB(raw)
	if len(got) != 1 || got[0].mac.String() != "c8:4f:86:a5:52:30" || got[0].portNo != 2 || got[0].idleSeconds != 12 {
		t.Fatalf("unexpected %+v", got)
	}
}
