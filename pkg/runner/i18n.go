package runner

// Lightweight i18n for the system-tray UI. The tray is the only user-facing
// surface in this process, so the catalog lives here rather than in a shared
// package. No external i18n framework: a per-language map of format templates
// and a tiny T() that formats the active language's template (falling back to
// English) is enough for a handful of short menu strings.
//
// Locale detection is per-GOOS (see i18n_windows.go / i18n_other.go). The
// WANTASTIC_LANG env var overrides detection for testing and support.

import (
	"fmt"
	"os"
	"strings"
	"sync"
)

// envLang reads an environment variable; a seam so detection stays testable.
func envLang(key string) string { return os.Getenv(key) }

// defaultLang is the base language and the fallback for any missing key or
// unsupported locale.
const defaultLang = "en"

// supportedLangs is the set T() can switch to, keyed by primary subtag.
var supportedLangs = map[string]bool{
	"en": true,
	"fr": true,
	"ar": true,
	"es": true,
	"de": true,
}

var (
	langMu     sync.RWMutex
	activeLang string // "" until first resolved
)

// currentLang returns the active language, resolving it once from
// WANTASTIC_LANG / the OS locale on first use.
func currentLang() string {
	langMu.RLock()
	l := activeLang
	langMu.RUnlock()
	if l != "" {
		return l
	}
	langMu.Lock()
	defer langMu.Unlock()
	if activeLang == "" {
		activeLang = resolveLang()
	}
	return activeLang
}

// forceLang overrides the active language. Used by tests for determinism and
// available for support tooling; normal code never calls it.
func forceLang(code string) {
	langMu.Lock()
	activeLang = code
	langMu.Unlock()
}

// resolveLang picks the active language: WANTASTIC_LANG first, then the OS
// locale, then English.
func resolveLang() string {
	if code := normalizeLang(envLang("WANTASTIC_LANG")); code != "" {
		return code
	}
	if code := normalizeLang(detectLocale()); code != "" {
		return code
	}
	return defaultLang
}

// normalizeLang maps a locale string ("fr-FR", "es_ES.UTF-8", "ar@foo") to a
// supported primary subtag, or "" if none matches.
func normalizeLang(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	if s == "" {
		return ""
	}
	primary := strings.FieldsFunc(s, func(r rune) bool {
		return r == '-' || r == '_' || r == '.' || r == '@' || r == ' '
	})
	if len(primary) == 0 {
		return ""
	}
	if supportedLangs[primary[0]] {
		return primary[0]
	}
	return ""
}

// T formats the active language's template for key, falling back to the
// English template, then to the key itself if nothing is found.
func T(key string, args ...any) string {
	return translate(currentLang(), key, args...)
}

// translate is T for an explicit language; tests use it to exercise each
// language without mutating global state.
func translate(lang, key string, args ...any) string {
	tmpl := lookup(lang, key)
	if tmpl == "" {
		tmpl = lookup(defaultLang, key)
	}
	if tmpl == "" {
		return key
	}
	// With no args a template is returned verbatim: this also keeps a template
	// that happens to contain a stray verb from being mangled, and keeps the
	// go vet "non-constant format string" check satisfied.
	if len(args) == 0 {
		return tmpl
	}
	return fmt.Sprintf(tmpl, args...)
}

func lookup(lang, key string) string {
	if m, ok := catalog[lang]; ok {
		if s, ok := m[key]; ok {
			return s
		}
	}
	return ""
}

