func main() {
	configPath := flag.String("config", auth.DefaultConfigPath(), "Path to configuration file")
	claimKeyPath := flag.String("claim-key", defaultClaimKeyPath(), "Path to device claim key JSON")
	serverURL := flag.String("server-url", "", "Wantastic server URL/domain used while waiting for claim")
	onboardAddr := flag.String("onboard", ":9043", "Address for the QR onboarding page")
	noOnboard := flag.Bool("no-onboard", false, "Disable the onboarding HTTP page")
	// Proxy mode: manage a remote FOS OLT through its goform API. When set,
	// the WUSP data model reports the OLT (Device.WUSP_OLT.*) instead of the
	// local host.
	oltURL := flag.String("olt-url", "", "FOS OLT web API base URL for proxy management (e.g. http://192.168.100.100)")
	oltUser := flag.String("olt-user", "admin", "OLT web API user")
	oltPass := flag.String("olt-pass", "admin", "OLT web API password")
	// OLT shell channel for operations the web API cannot do (claim reset).
	oltShellHost := flag.String("olt-shell", "", "OLT debug telnet address (host:port) for claim reset operations")
	oltShellUser := flag.String("olt-shell-user", "debug", "OLT debug shell user")
	oltShellPass := flag.String("olt-shell-pass", "", "OLT debug shell password")
	corsOrigin := flag.String("cors-origin", "http://192.168.100.100", "Browser origin allowed to call the proxy bridge")
	flag.Parse()

	log.SetFlags(log.LstdFlags)
	log.Printf("fiberagent %s starting", version.Version)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	sigCh := make(chan os.Signal, 1)
	signal.Notify(sigCh, syscall.SIGINT, syscall.SIGTERM)
	go func() {
		<-sigCh
		log.Println("Received shutdown signal")
		cancel()
	}()

	var onboard *atomic.Pointer[onboardingState]
	var shell *oltShell
	if *oltShellHost != "" {
		shell = &oltShell{host: *oltShellHost, user: *oltShellUser, pass: *oltShellPass}
	}
	if !*noOnboard {
		onboard = serveOnboarding(*onboardAddr, *corsOrigin, shell)
	}

	cfg, err := config.LoadFromFile(*configPath)
	if err == nil {
		applyOLTFlags(cfg, *oltURL, *oltUser, *oltPass)
		markClaimed(onboard, "")
		runAgent(ctx, cfg)
		return
	}

	// Unclaimed: generate (or reuse) the claim key, show the QR, and wait
	// for the claim to complete.
	portalURL := auth.NormalizeServerURL(*serverURL)
	keyFile, reused, err := loadOrCreateClaimKey(*claimKeyPath, portalURL, false)
	if err != nil {
		log.Fatalf("claim key: %v", err)
	}
	if reused {
		log.Printf("Reused existing device claim key: %s", *claimKeyPath)
	} else {
		log.Printf("Generated device claim key: %s", *claimKeyPath)
	}
	if err := auth.PersistPublicKey(keyFile.PublicKey); err != nil {
		log.Printf("Warning: could not persist public key copy: %v", err)
	}
	markClaimed(onboard, "")
	setOnboard(onboard, &onboardingState{
		ClaimURL:  keyFile.ClaimURL,
		PublicKey: keyFile.PublicKey,
	})
	log.Printf("Claim URL: %s", keyFile.ClaimURL)

	log.Printf("computing device id...")
	hashedDeviceID, err := auth.HashedDeviceID()
	if err != nil {
		log.Fatalf("device id: %v", err)
	}
	log.Printf("device id ready, fetching claim config...")

	// The device may already be claimed (e.g. by scanning the QR on the OLT
	// web UI). Fetch the claim config directly in that case; otherwise wait
	// for the claim to happen.
	claim, err := auth.FetchClaimConfig(ctx, portalURL, hashedDeviceID, keyFile.PublicKey)
	log.Printf("claim fetch result: err=%v claimed=%v", err, claim != nil && claim.Claimed)
	if err != nil || claim == nil || !claim.Claimed {
		if err != nil {
			log.Printf("claim config not ready yet: %v", err)
		}
		// The claim-wait socket can drop (proxy restarts, NAT timeouts);
		// keep reconnecting until the claim arrives or the context ends.
		waitErr := error(nil)
		for attempt := 1; ; attempt++ {
			claim, waitErr = auth.WaitClaimConfig(ctx, portalURL, hashedDeviceID, keyFile.PublicKey)
			if waitErr == nil && claim != nil && claim.Claimed {
				break
			}
			if ctx.Err() != nil {
				break
			}
			backoff := time.Duration(attempt) * 5 * time.Second
			if backoff > 60*time.Second {
				backoff = 60 * time.Second
			}
			log.Printf("claim wait attempt %d failed (%v); retrying in %s", attempt, waitErr, backoff)
			select {
			case <-ctx.Done():
			case <-time.After(backoff):
			}
		}
		if waitErr != nil || claim == nil || !claim.Claimed {
			setOnboard(onboard, &onboardingState{
				ClaimURL:  keyFile.ClaimURL,
				PublicKey: keyFile.PublicKey,
				Message:   "claim wait failed: " + fmt.Sprint(waitErr),
			})
			log.Fatalf("claim: %v", waitErr)
		}
	}

	cfg, err = config.LoadFromClaimConfig(portalURL, keyFile.PrivateKey, keyFile.PublicKey, claim)
	if err != nil {
		log.Fatalf("load claimed config: %v", err)
	}
	applyOLTFlags(cfg, *oltURL, *oltUser, *oltPass)
	if err := cfg.SaveToFile(*configPath); err != nil {
		log.Printf("Warning: could not persist claimed config: %v", err)
	}
	markClaimed(onboard, "")
	log.Printf("Device claimed, starting agent")
	runAgent(ctx, cfg)
}

// applyOLTFlags enables OLT proxy management when -olt-url is given.
func applyOLTFlags(cfg *config.Config, url, user, pass string) {
	if url == "" {
		return
	}
	cfg.OLT = config.OLT{Enable: true, URL: url, User: user, Password: pass}
	log.Printf("OLT proxy management enabled: %s", url)
}

func runAgent(ctx context.Context, cfg *config.Config) {
	agt, err := agent.New(cfg)
	if err != nil {
		log.Fatalf("create agent: %v", err)
	}
	if err := agt.Start(ctx); err != nil {
		log.Fatalf("start agent: %v", err)
	}
	log.Printf("fiberagent started (tun=%q port=%d)", cfg.Interface.TUNName, cfg.Interface.ListenPort)
	<-ctx.Done()
	if err := agt.Stop(); err != nil {
		log.Printf("stop agent: %v", err)
	}
	log.Println("fiberagent stopped")
}

// ---- onboarding page ---------------------------------------------------

func serveOnboarding(addr, corsOrigin string, shell *oltShell) *atomic.Pointer[onboardingState] {
	state := &atomic.Pointer[onboardingState]{}
	state.Store(&onboardingState{})

	mux := http.NewServeMux()
	bridge := newProxyBridge("http://127.0.0.1:9034", corsOrigin)
	bridge.register(mux)
	mux.HandleFunc("/api/olt/reset", func(w http.ResponseWriter, r *http.Request) {
		bridge.corsHeaders(w, r)
		if r.Method == http.MethodOptions {
			w.WriteHeader(http.StatusNoContent)
			return
		}
		if r.Method != http.MethodPost {
			http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
			return
		}
		if shell == nil {
			marshalOK(w, map[string]any{"ok": false, "error": "olt shell not configured"})
			return
		}
		if err := shell.resetOLTClaim(); err != nil {
			marshalOK(w, map[string]any{"ok": false, "error": err.Error()})
			return
		}
		marshalOK(w, map[string]any{"ok": true})
	})
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/" {
			http.NotFound(w, r)
			return
		}
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		_ = onboardingPage.Execute(w, state.Load())
	})
	mux.HandleFunc("/qr.png", func(w http.ResponseWriter, r *http.Request) {
		claimURL := state.Load().ClaimURL
		if claimURL == "" {
			http.NotFound(w, r)
			return
		}
		code, err := qr.Encode(claimURL, qr.L)
		if err != nil {
			http.Error(w, "qr encode failed", http.StatusInternalServerError)
			return
		}
		w.Header().Set("Content-Type", "image/png")
		w.Header().Set("Cache-Control", "no-store")
		_ = png.Encode(w, code.Image())
	})
	mux.HandleFunc("/status", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(state.Load())
	})

	server := &http.Server{Addr: addr, Handler: mux, ReadHeaderTimeout: 5 * time.Second}
	go func() {
		if err := server.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			log.Printf("onboarding page: %v", err)
		}
	}()
	log.Printf("Onboarding page listening on %s", addr)
	return state
}

func setOnboard(state *atomic.Pointer[onboardingState], next *onboardingState) {
	if state != nil {
		state.Store(next)
	}
}

func markClaimed(state *atomic.Pointer[onboardingState], message string) {
	if state == nil {
		return
	}
	prev := state.Load()
	setOnboard(state, &onboardingState{
		ClaimURL:  prev.ClaimURL,
		PublicKey: prev.PublicKey,
		Claimed:   true,
		Message:   message,
	})
}

// ---- claim key helpers (mirrors cmd/wantasticd) ------------------------

func defaultClaimKeyPath() string {
	return auth.PersistentFilePath("device-claim-key.json")
}

func loadOrCreateClaimKey(path, portalBaseURL string, force bool) (*claimKeyFile, bool, error) {
	if !force {
		if data, err := os.ReadFile(path); err == nil {
			var existing claimKeyFile
			if err := json.Unmarshal(data, &existing); err != nil {
				return nil, false, fmt.Errorf("parse existing key file: %w", err)
			}
			if existing.PrivateKey == "" || existing.PublicKey == "" {
				return nil, false, fmt.Errorf("existing key file missing private_key or public_key")
			}
			existing.ServerURL = portalBaseURL
			existing.ClaimURL = auth.BuildClaimURL(portalBaseURL, existing.PublicKey, "")
			if err := writeClaimKeyFile(path, &existing); err != nil {
				return nil, false, fmt.Errorf("update existing key file: %w", err)
			}
			return &existing, true, nil
		} else if !os.IsNotExist(err) {
			return nil, false, fmt.Errorf("read key file: %w", err)
		}
	}

	privateKey, publicKey, err := generateWireGuardKeyPair()
	if err != nil {
		return nil, false, err
	}
	keyFile := &claimKeyFile{
		PrivateKey: privateKey,
		PublicKey:  publicKey,
		ServerURL:  portalBaseURL,
		ClaimURL:   auth.BuildClaimURL(portalBaseURL, publicKey, ""),
		CreatedAt:  time.Now().UTC().Format(time.RFC3339),
	}
	if err := writeClaimKeyFile(path, keyFile); err != nil {
		return nil, false, err
	}
	return keyFile, false, nil
}

func writeClaimKeyFile(path string, keyFile *claimKeyFile) error {
	data, err := json.MarshalIndent(keyFile, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o600)
}

// generateWireGuardKeyPair mirrors cmd/wantasticd's key generation so
// claim keys are interchangeable between the daemons.
func generateWireGuardKeyPair() (string, string, error) {
	privateBytes := make([]byte, 32)
	if _, err := rand.Read(privateBytes); err != nil {
		return "", "", fmt.Errorf("generate private key: %w", err)
	}
	privateBytes[0] &= 248
	privateBytes[31] = (privateBytes[31] & 127) | 64

	publicBytes, err := curve25519.X25519(privateBytes, curve25519.Basepoint)
	if err != nil {
		return "", "", fmt.Errorf("derive public key: %w", err)
	}
	return base64.StdEncoding.EncodeToString(privateBytes), base64.StdEncoding.EncodeToString(publicBytes), nil
}
