func TestCollectDNS(t *testing.T) {
	dir := t.TempDir()
	resolv := filepath.Join(dir, "resolv.conf")
	os.WriteFile(resolv, []byte(`search example.com
nameserver 8.8.8.8
nameserver 1.1.1.1
`), 0644)

	// Test the DNS parser by writing to a known path
	msg := wusp.NewMessage()
	data, _ := os.ReadFile(resolv)
	lines := make([]string, 0)
	for _, line := range splitLines(string(data)) {
		lines = append(lines, line)
	}
	// Simulate collectDNS logic
	idx := 1
	for _, line := range lines {
		line = trimSpace(line)
		if hasPrefix(line, "nameserver") {
			fields := splitFields(line)
			if len(fields) >= 2 {
				msg.Set(netPrefix+"DNS.Server."+itoa(idx)+".Address", wusp.String(fields[1]))
				idx++
			}
		} else if hasPrefix(line, "search") {
			fields := splitFields(line)
			if len(fields) >= 2 {
				msg.Set(netPrefix+"DNS.SearchDomain", wusp.String(fields[1]))
			}
		}
	}
	msg.Set(netPrefix+"DNS.ServerNumberOfEntries", wusp.Uint(uint64(idx-1)))

	v, ok := msg.Get(netPrefix + "DNS.Server.1.Address")
	if !ok || wusp.ValueToString(v) != "8.8.8.8" {
		t.Errorf("DNS server 1: got %v", v)
	}
	v, ok = msg.Get(netPrefix + "DNS.Server.2.Address")
	if !ok || wusp.ValueToString(v) != "1.1.1.1" {
		t.Errorf("DNS server 2: got %v", v)
	}
	v, ok = msg.Get(netPrefix + "DNS.SearchDomain")
	if !ok || wusp.ValueToString(v) != "example.com" {
		t.Errorf("DNS search domain: got %v", v)
	}
}

func TestParseStationDump(t *testing.T) {
	dump := `Station aa:bb:cc:dd:ee:ff (on wlan0)
	inactive time:	30 ms
	rx bytes:	123456
	tx bytes:	654321
	signal:  	-65 dBm
	rx bitrate:	72.2 MBit/s
	tx bitrate:	144.4 MBit/s
	connected time:	3600 seconds
Station 11:22:33:44:55:66 (on wlan0)
	signal:  	-80 dBm
	rx bytes:	5000
	tx bytes:	3000
`
	stations := parseStationDump(dump)
	if len(stations) != 2 {
		t.Fatalf("expected 2 stations, got %d", len(stations))
	}
	if stations[0].mac != "aa:bb:cc:dd:ee:ff" {
		t.Errorf("station 0 mac = %q", stations[0].mac)
	}
	if stations[0].signal != "-65 dBm" {
		t.Errorf("station 0 signal = %q", stations[0].signal)
	}
	if stations[0].rxBytes != 123456 {
		t.Errorf("station 0 rxBytes = %d", stations[0].rxBytes)
	}
	if stations[0].connected != "3600 seconds" {
		t.Errorf("station 0 connected = %q", stations[0].connected)
	}
	if stations[1].mac != "11:22:33:44:55:66" {
		t.Errorf("station 1 mac = %q", stations[1].mac)
	}
}

func TestCollectIPTables(t *testing.T) {
	// Test the parsing logic directly — iptables-save won't work in test
	msg := wusp.NewMessage()
	out := `# Generated by iptables-save
*filter
:INPUT ACCEPT [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
-A INPUT -i lo -j ACCEPT
-A INPUT -m state --state ESTABLISHED,RELATED -j ACCEPT
-A FORWARD -i eth0 -o wlan0 -j ACCEPT
COMMIT`
	// Simulate collectOneIPTable
	idx := 1
	for _, line := range splitLines(out) {
		line = trimSpace(line)
		if line == "" || hasPrefix(line, "#") || hasPrefix(line, "*") || line == "COMMIT" {
			continue
		}
		row := netPrefix + "Firewall.Rule." + itoa(idx) + "."
		msg.Set(row+"Table", wusp.String("filter"))
		if hasPrefix(line, ":") {
			fields := splitFields(line[1:])
			if len(fields) >= 2 {
				msg.Set(row+"Chain", wusp.String(fields[0]))
				msg.Set(row+"Policy", wusp.String(fields[1]))
				msg.Set(row+"Type", wusp.String("policy"))
			}
		} else if hasPrefix(line, "-A") {
			msg.Set(row+"Raw", wusp.String(line))
			fields := splitFields(line)
			if len(fields) >= 2 {
				msg.Set(row+"Chain", wusp.String(fields[1]))
			}
			msg.Set(row+"Type", wusp.String("rule"))
		} else {
			continue
		}
		idx++
	}
	msg.Set(netPrefix+"Firewall.RuleNumberOfEntries", wusp.Uint(uint64(idx-1)))

	assertField := func(path, want string) {
		t.Helper()
		v, ok := msg.Get(path)
		if !ok {
			t.Errorf("missing %s", path)
			return
		}
		got := wusp.ValueToString(v)
		if got != want {
			t.Errorf("%s = %q, want %q", path, got, want)
		}
	}
	assertField(netPrefix+"Firewall.RuleNumberOfEntries", "6")
	assertField(netPrefix+"Firewall.Rule.1.Chain", "INPUT")
	assertField(netPrefix+"Firewall.Rule.1.Policy", "ACCEPT")
	assertField(netPrefix+"Firewall.Rule.1.Type", "policy")
	assertField(netPrefix+"Firewall.Rule.2.Chain", "FORWARD")
	assertField(netPrefix+"Firewall.Rule.2.Policy", "DROP")
	assertField(netPrefix+"Firewall.Rule.4.Type", "rule")
	assertField(netPrefix+"Firewall.Rule.4.Chain", "INPUT")
}

