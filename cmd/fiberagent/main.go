// Command fiberagent is the slim Wantastic agent for fiber devices:
// FOS-based GPON OLTs (and later ONUs) where the full desktop daemon does
// not fit. It provides the device claim flow with a QR onboarding page,
// then runs the standard agent (WireGuard mesh + WUSP control plane) with
// the OLT platform backend auto-detected.
//
// Flags:
//
//	-config      path to the claimed configuration file (default: the
//	             standard persistent config path)
//	-claim-key   path to the device claim key JSON (default: persistent
//	             device-claim-key.json)
//	-server-url  Wantastic server URL/domain for the claim flow (empty:
//	             the default Wantastic cloud)
//	-onboard     address for the QR onboarding page (default ":9043")
//	-no-onboard  disable the onboarding HTTP page
package main

