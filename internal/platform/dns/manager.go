package dns

import (
	"net"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// Linux DNS manager detection. An installed tool is not proof that it owns
// the resolver: nmcli and resolvconf ship on many images where NetworkManager
// is not running or /etc/resolv.conf is a plain file, and treating them as
// the manager made every read report an error and every write fail. Each
// manager is only selected when /etc/resolv.conf (or a running daemon) shows
// that it is in charge.
//
// The detection is platform-neutral (it only reads files) so its tests run
// everywhere; only Linux calls it.

var (
	openWrtReleasePath = "/etc/openwrt_release"
	procRoot           = "/proc"
	statPath           = os.Stat
	// resolvedUpstreamPath lists systemd-resolved's real upstreams.
	resolvedUpstreamPath = "/run/systemd/resolve/resolv.conf"
)

const (
	managerOpenWrt         = "openwrt-uci"
	managerResolved        = "systemd-resolved"
	managerNetworkManager  = "networkmanager"
	managerResolvconf      = "resolvconf"
	managerDnsmasq         = "dnsmasq"
	managerManagedResolv   = "managed-resolv.conf"
	managerPlainFile       = "plain-file"
	managerVolatileFile    = "volatile-file"
	resolvedStubNameserver = "127.0.0.53"
)

func detectLinuxDNSManager() string {
	if _, err := statPath(openWrtReleasePath); err == nil {
		return managerOpenWrt
	}
	link := resolvConfLink()
	content := ""
	if data, err := readFile(resolvConfPath); err == nil {
		content = string(data)
	}
	nameservers := parseNameserverLines(content)

	if strings.Contains(link, "systemd/resolve") ||
		(containsString(nameservers, resolvedStubNameserver) && resolvedRunning()) {
		return managerResolved
	}
	if commandAvailable("nmcli") && processRunning("NetworkManager") &&
		(strings.Contains(link, "NetworkManager") || strings.Contains(content, "Generated by NetworkManager")) {
		return managerNetworkManager
	}
	if commandAvailable("resolvconf") &&
		(strings.Contains(link, "resolvconf") || strings.Contains(strings.ToLower(content), "generated by resolvconf")) {
		return managerResolvconf
	}
	if link != "" && isManagedResolvTarget(link) {
		return managerManagedResolv
	}
	if allLoopback(nameservers) && len(dnsmasqPIDs()) > 0 {
		return managerDnsmasq
	}
	if link != "" {
		return managerVolatileFile
	}
	return managerPlainFile
}

// resolvConfLink returns the symlink target of /etc/resolv.conf, or "".
func resolvConfLink() string {
	fi, err := lstatPath(resolvConfPath)
	if err != nil || fi.Mode()&os.ModeSymlink == 0 {
		return ""
	}
	target, err := os.Readlink(resolvConfPath)
	if err != nil {
		return ""
	}
	return target
}

func resolvedRunning() bool {
	if _, err := statPath(resolvedUpstreamPath); err == nil {
		return true
	}
	// comm is truncated to 15 bytes: "systemd-resolve".
	return processRunning("systemd-resolve")
}

func containsString(items []string, want string) bool {
	for _, item := range items {
		if item == want {
			return true
		}
	}
	return false
}

func allLoopback(servers []string) bool {
	if len(servers) == 0 {
		return false
	}
	for _, server := range servers {
		ip := net.ParseIP(strings.TrimSpace(server))
		if ip == nil || !ip.IsLoopback() || server == resolvedStubNameserver {
			return false
		}
	}
	return true
}

// processPIDs lists processes whose /proc/<pid>/comm is name.
func processPIDs(name string) []int {
	entries, err := os.ReadDir(procRoot)
	if err != nil {
		return nil
	}
	var out []int
	for _, entry := range entries {
		pid, err := strconv.Atoi(entry.Name())
		if err != nil || pid <= 0 {
			continue
		}
		comm, err := readFile(filepath.Join(procRoot, entry.Name(), "comm"))
		if err == nil && strings.TrimSpace(string(comm)) == name {
			out = append(out, pid)
		}
	}
	return out
}

func processRunning(name string) bool { return len(processPIDs(name)) > 0 }

func dnsmasqPIDs() []int { return processPIDs("dnsmasq") }

// dnsmasqUpstreams returns the upstream resolvers of the running dnsmasq
// instances: server= entries (domain-specific forwarders excluded) and,
// unless no-resolv is set, the nameservers of its resolv-file. Loopback
// addresses (dnsmasq itself) are skipped.
func dnsmasqUpstreams() []string {
	var out []string
	seen := map[string]bool{}
	add := func(server string) {
		ip := net.ParseIP(server)
		if ip == nil || ip.IsLoopback() || ip.IsUnspecified() || seen[ip.String()] {
			return
		}
		seen[ip.String()] = true
		out = append(out, ip.String())
	}
	for _, pid := range dnsmasqPIDs() {
		raw, err := readFile(filepath.Join(procRoot, strconv.Itoa(pid), "cmdline"))
		if err != nil {
			continue
		}
		cfg := parseDnsmasqArgs(strings.Split(strings.TrimRight(string(raw), "\x00"), "\x00"))
		for _, server := range cfg.servers {
			add(server)
		}
		if !cfg.noResolv {
			for _, server := range readResolvNameservers(cfg.resolvFile) {
				add(server)
			}
		}
	}
	return out
}

type dnsmasqConfig struct {
	servers    []string
	resolvFile string
	noResolv   bool
}

// parseDnsmasqArgs reads the resolver-relevant options from a dnsmasq
// command line and the conf-file it names (default /etc/dnsmasq.conf).
func parseDnsmasqArgs(args []string) dnsmasqConfig {
	cfg := dnsmasqConfig{}
	confFiles := []string{}
	explicitConf := false
	apply := func(key, value string) {
		switch key {
		case "server", "S":
			if server := dnsmasqServerAddress(value); server != "" {
				cfg.servers = append(cfg.servers, server)
			}
		case "resolv-file", "r":
			if value != "" {
				cfg.resolvFile = value
			}
		case "no-resolv", "R":
			cfg.noResolv = true
		case "conf-file", "C":
			explicitConf = true
			if value != "" {
				confFiles = append(confFiles, value)
			}
		}
	}
	for i := 1; i < len(args); i++ {
		arg := strings.TrimSpace(args[i])
		switch {
		case strings.HasPrefix(arg, "--"):
			key, value, _ := strings.Cut(strings.TrimPrefix(arg, "--"), "=")
			apply(key, value)
		case strings.HasPrefix(arg, "-") && len(arg) >= 2:
			key, value := arg[1:2], arg[2:]
			if value == "" && key != "R" && i+1 < len(args) && !strings.HasPrefix(args[i+1], "-") {
				value = args[i+1]
				i++
			}
			apply(key, value)
		}
	}
	if !explicitConf {
		confFiles = append(confFiles, "/etc/dnsmasq.conf")
	}
	for _, path := range confFiles {
		data, err := readFile(path)
		if err != nil {
			continue
		}
		for _, line := range strings.Split(string(data), "\n") {
			line = strings.TrimSpace(line)
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			key, value, _ := strings.Cut(line, "=")
			switch key = strings.TrimSpace(key); key {
			case "server", "resolv-file", "no-resolv":
				apply(key, strings.TrimSpace(value))
			}
		}
	}
	if cfg.resolvFile == "" {
		cfg.resolvFile = "/etc/resolv.conf"
	}
	return cfg
}

// dnsmasqServerAddress returns the plain upstream of a server= value, or ""
// for a domain-specific forwarder (/domain/ip) or a non-address.
func dnsmasqServerAddress(value string) string {
	value = strings.TrimSpace(value)
	if value == "" || strings.HasPrefix(value, "/") {
		return ""
	}
	if i := strings.IndexAny(value, "#@"); i >= 0 {
		value = value[:i]
	}
	if net.ParseIP(value) == nil {
		return ""
	}
	return value
}
