package dns

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// dnsTestEnv points every system path the detector reads at a temp tree.
type dnsTestEnv struct {
	dir  string
	proc string
	bins map[string]bool
}

func newDNSTestEnv(t *testing.T) *dnsTestEnv {
	t.Helper()
	dir := t.TempDir()
	env := &dnsTestEnv{dir: dir, proc: filepath.Join(dir, "proc"), bins: map[string]bool{}}
	if err := os.MkdirAll(env.proc, 0o755); err != nil {
		t.Fatal(err)
	}
	oldResolv, oldRelease, oldProc, oldLook, oldUpstream := resolvConfPath, openWrtReleasePath, procRoot, lookPath, resolvedUpstreamPath
	t.Cleanup(func() {
		resolvConfPath, openWrtReleasePath, procRoot, lookPath, resolvedUpstreamPath = oldResolv, oldRelease, oldProc, oldLook, oldUpstream
	})
	resolvConfPath = filepath.Join(dir, "etc", "resolv.conf")
	openWrtReleasePath = filepath.Join(dir, "etc", "openwrt_release")
	resolvedUpstreamPath = filepath.Join(dir, "run", "systemd", "resolve", "resolv.conf")
	procRoot = env.proc
	lookPath = func(name string) (string, error) {
		if env.bins[name] {
			return "/usr/bin/" + name, nil
		}
		return "", os.ErrNotExist
	}
	return env
}

func (e *dnsTestEnv) write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func (e *dnsTestEnv) process(t *testing.T, pid, comm string, args ...string) {
	t.Helper()
	e.write(t, filepath.Join(e.proc, pid, "comm"), comm+"\n")
	e.write(t, filepath.Join(e.proc, pid, "cmdline"), strings.Join(args, "\x00")+"\x00")
}

func (e *dnsTestEnv) linkResolv(t *testing.T, target, content string) {
	t.Helper()
	if content != "" {
		e.write(t, target, content)
	}
	if err := os.MkdirAll(filepath.Dir(resolvConfPath), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, resolvConfPath); err != nil {
		t.Fatal(err)
	}
}

func TestDetectDNSManagerInstalledToolsDoNotWin(t *testing.T) {
	env := newDNSTestEnv(t)
	env.bins["nmcli"], env.bins["resolvconf"], env.bins["resolvectl"] = true, true, true
	env.write(t, resolvConfPath, "nameserver 10.0.0.1\n")
	if got := detectLinuxDNSManager(); got != managerPlainFile {
		t.Fatalf("installed but idle managers: got %q, want plain-file", got)
	}

	env.process(t, "42", "NetworkManager", "/usr/sbin/NetworkManager")
	if got := detectLinuxDNSManager(); got != managerPlainFile {
		t.Fatalf("NetworkManager running without owning resolv.conf: got %q", got)
	}
	env.write(t, resolvConfPath, "# Generated by NetworkManager\nnameserver 10.0.0.1\n")
	if got := detectLinuxDNSManager(); got != managerNetworkManager {
		t.Fatalf("NetworkManager-generated file: got %q", got)
	}
}

func TestDetectDNSManagerOwners(t *testing.T) {
	t.Run("resolvconf header", func(t *testing.T) {
		env := newDNSTestEnv(t)
		env.bins["resolvconf"] = true
		env.write(t, resolvConfPath, "# Dynamic resolv.conf(5) file for glibc resolver(3) generated by resolvconf(8)\nnameserver 10.0.0.1\n")
		if got := detectLinuxDNSManager(); got != managerResolvconf {
			t.Fatalf("got %q", got)
		}
	})
	t.Run("resolved stub", func(t *testing.T) {
		env := newDNSTestEnv(t)
		env.write(t, resolvConfPath, "nameserver 127.0.0.53\n")
		if got := detectLinuxDNSManager(); got != managerPlainFile {
			t.Fatalf("stub without resolved: got %q", got)
		}
		env.write(t, resolvedUpstreamPath, "nameserver 10.0.0.1\n")
		if got := detectLinuxDNSManager(); got != managerResolved {
			t.Fatalf("stub with resolved: got %q", got)
		}
	})
	t.Run("resolved symlink", func(t *testing.T) {
		env := newDNSTestEnv(t)
		env.linkResolv(t, filepath.Join(env.dir, "run", "systemd", "resolve", "stub-resolv.conf"), "nameserver 127.0.0.53\n")
		if got := detectLinuxDNSManager(); got != managerResolved {
			t.Fatalf("got %q", got)
		}
	})
	t.Run("volatile symlink", func(t *testing.T) {
		env := newDNSTestEnv(t)
		env.linkResolv(t, filepath.Join(env.dir, "var", "run", "resolv.conf"), "nameserver 10.0.0.1\n")
		if got := detectLinuxDNSManager(); got != managerVolatileFile {
			t.Fatalf("got %q", got)
		}
	})
	t.Run("local dnsmasq", func(t *testing.T) {
		env := newDNSTestEnv(t)
		env.write(t, resolvConfPath, "nameserver 127.0.0.1\n")
		if got := detectLinuxDNSManager(); got != managerPlainFile {
			t.Fatalf("loopback without dnsmasq: got %q", got)
		}
		env.process(t, "77", "dnsmasq", "dnsmasq", "-C", filepath.Join(env.dir, "none.conf"))
		if got := detectLinuxDNSManager(); got != managerDnsmasq {
			t.Fatalf("got %q", got)
		}
	})
	t.Run("openwrt", func(t *testing.T) {
		env := newDNSTestEnv(t)
		env.write(t, openWrtReleasePath, "DISTRIB_ID='OpenWrt'\n")
		if got := detectLinuxDNSManager(); got != managerOpenWrt {
			t.Fatalf("got %q", got)
		}
	})
}

func TestDnsmasqUpstreams(t *testing.T) {
	env := newDNSTestEnv(t)
	upstream := filepath.Join(env.dir, "data", "dnsmasq.resolv")
	env.write(t, upstream, "nameserver 10.20.0.1\nnameserver 127.0.0.1\nnameserver 2001:db8::53\n")
	conf := filepath.Join(env.dir, "etc", "dnsmasq.conf")
	env.write(t, conf, "# QCMAP\nserver=/corp.example/10.9.9.9\nserver=9.9.9.9#53\nresolv-file="+upstream+"\n")
	env.process(t, "100", "dnsmasq", "dnsmasq", "--conf-file="+conf, "-S", "8.8.4.4")

	got := dnsmasqUpstreams()
	want := []string{"8.8.4.4", "9.9.9.9", "10.20.0.1", "2001:db8::53"}
	if !sameServers(got, want) {
		t.Fatalf("upstreams = %v, want %v", got, want)
	}

	cfg := parseDnsmasqArgs([]string{"dnsmasq", "-R", "--server=1.1.1.1", "-C", conf})
	if !cfg.noResolv || len(cfg.servers) != 2 || cfg.servers[0] != "1.1.1.1" {
		t.Fatalf("parsed %+v", cfg)
	}
}

func TestWriteResolvFileThroughSymlinkKeepsLinkAndMarker(t *testing.T) {
	env := newDNSTestEnv(t)
	target := filepath.Join(env.dir, "var", "run", "resolv.conf")
	env.linkResolv(t, target, "nameserver 10.0.0.1\n")

	if _, err := writeResolvFileManual(resolvConfPath, []string{"9.9.9.9"}, controlReason, []string{"9.9.9.9"}); err != nil {
		t.Fatal(err)
	}
	if fi, err := os.Lstat(resolvConfPath); err != nil || fi.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("resolv.conf link replaced: %v", err)
	}
	if got := readResolvNameservers(target); !sameServers(got, []string{"9.9.9.9"}) {
		t.Fatalf("target nameservers = %v", got)
	}

	// The periodic tunnel rewrite keeps the console's manual marker.
	if _, err := writeResolvFile(resolvConfPath, []string{"10.99.0.1", "9.9.9.9"}, "tunnel DNS"); err != nil {
		t.Fatal(err)
	}
	if got := readManualMarker(resolvConfPath); !sameServers(got, []string{"9.9.9.9"}) {
		t.Fatalf("manual marker after tunnel rewrite = %v", got)
	}
}

func TestReadManualMarkerLegacyHeader(t *testing.T) {
	env := newDNSTestEnv(t)
	env.write(t, resolvConfPath, "# Managed by wantasticd for DNS control\nnameserver 1.1.1.1\n")
	if got := readManualMarker(resolvConfPath); !sameServers(got, []string{"1.1.1.1"}) {
		t.Fatalf("legacy manual = %v", got)
	}
	env.write(t, resolvConfPath, "# Managed by wantasticd for tunnel DNS\nnameserver 1.1.1.1\n")
	if got := readManualMarker(resolvConfPath); len(got) != 0 {
		t.Fatalf("tunnel header read as manual: %v", got)
	}
}

