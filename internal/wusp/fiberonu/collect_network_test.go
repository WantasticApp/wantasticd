func TestCollectInterfaces(t *testing.T) {
	dir := t.TempDir()
	procNetDev := filepath.Join(dir, "proc_net_dev")
	os.WriteFile(procNetDev, []byte(`Inter-|   Receive                                                |  Transmit
 face |bytes    packets errs drop fifo frame compressed multicast|bytes    packets errs drop fifo colls carrier compressed
    lo: 1234567     100    0    0    0     0          0         0  1234567     100    0    0    0     0       0          0
  eth0: 9876543    2000    5    0    0     0          0         0  5432109    1500    2    0    0     0       0          0
`), 0644)

	// Can't easily test collectInterfaces since it reads /proc/net/dev directly,
	// but we can test the hex-to-IP helper and station parser.
	t.Run("hexToIP", func(t *testing.T) {
		tests := []struct {
			hex  string
			want string
		}{
			{"00000000", "0.0.0.0"},
			{"0100007F", "127.0.0.1"},
			{"0101A8C0", "192.168.1.1"},
		}
		for _, tt := range tests {
			got := hexToIP(tt.hex)
			if got != tt.want {
				t.Errorf("hexToIP(%q) = %q, want %q", tt.hex, got, tt.want)
			}
		}
	})
}

